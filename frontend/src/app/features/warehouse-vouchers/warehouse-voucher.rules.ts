/** A voucher generated by another document must be cancelled from that document. */
type Doc = { id: string; code: string };
/** Lists to resolve a source document's code and link (DataStore fits). */
export interface SourceLookup {
  purchaseOrders(): Doc[];
  salesOrders(): Doc[];
  productionOrders(): Doc[];
  deliveryTrips(): Doc[];
}

const SOURCES = [
  { label: 'Đơn nhập hàng', idKey: 'purchaseOrderId', pattern: /theo đơn (DN\d+)/, path: '/mua-hang', list: (d: SourceLookup) => d.purchaseOrders() },
  { label: 'Đơn hàng bán', idKey: 'salesOrderId', pattern: null, path: '/don-hang', list: (d: SourceLookup) => d.salesOrders() },
  { label: 'Lệnh sản xuất', idKey: 'productionOrderId', pattern: /(LSX\d+)/, path: '/san-xuat', list: (d: SourceLookup) => d.productionOrders() },
  { label: 'Chuyến giao hàng', idKey: null, pattern: /chuyến (CH\d+)/, path: '/giao-hang', list: (d: SourceLookup) => d.deliveryTrips() },
] as const;

/**
 * Chứng từ gốc of a voucher generated by another document — by stored id, or (older/demo
 * vouchers) by the code in the reason. With `data`, code and link are resolved. Null = lập tay.
 */
export function sourceOf(v: WarehouseVoucher, data?: SourceLookup): { label: string; code?: string; link?: unknown[] } | null {
  for (const s of SOURCES) {
    const id = s.idKey ? v[s.idKey] : undefined;
    const code = !id && s.pattern ? s.pattern.exec(v.reason ?? '')?.[1] : undefined;
    if (!id && !code) continue;
    const doc = data ? s.list(data).find((d) => (id ? d.id === id : d.code === code)) : undefined;
    return { label: s.label, code: doc?.code ?? code, link: doc ? [s.path, doc.id] : id ? [s.path, id] : undefined };
  }
  return null;
}
